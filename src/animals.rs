//! The animal-name roster that gives each visitor an anonymous identity.
//!
//! Sorted, so a duplicate shows in review, and deduplicated, since two users
//! sharing a name in one room breaks the only identity the UI shows;
//! `animal_roster_is_sorted_unique_and_well_formed` enforces both.
//!
//! Entries must be animals. An earlier list ran off the end of a dictionary
//! and shipped `hadron`, `hagiology`, `halley`, `gyroscope`, `half-penny` and
//! `hallway` (and `hallingers` and `hallway` twice).

/// Whether `name` is one this server issues. The roster is the closed set of
/// display names, so a client's claim (a cookie, above all) is checked against
/// it rather than sanitised. `binary_search` is correct only because the
/// roster is sorted, which `animal_roster_is_sorted_unique_and_well_formed`
/// keeps true.
pub(crate) fn is_animal_name(name: &str) -> bool {
    ANIMAL_NAMES.binary_search(&name).is_ok()
}

